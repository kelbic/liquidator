"""У полла предиктора СВОЙ узел, и источник не врёт в журнале (#33).

Замер на Шарлотте за сутки 08-09.08: полл агрегаторов делил bg-ключ с прочими фоновыми
потребителями и собрал 226 отказов 429, из них 127 с экспоненциальным backoff — 1725с,
то есть ~29 МИНУТ в сутки слой упреждения не смотрел на агрегаторы. Слепнет при этом
именно та ось, на которой мы вообще можем выигрывать: реакцией гонку не берут (0/9794),
берут предвидением, а предвидение начинается с полла.

Экзаменуем выбор узла и ЧЕСТНОСТЬ его имени: строка журнала «узел=bg», за которой на деле
стоит боевой ключ, хуже отсутствия строки — по ней будут искать причину 429 не там.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from chain.predict import pick_poll_endpoint                # noqa: E402

COMBAT = "https://combat.example/base/KEY_COMBAT"
BG = "https://bg.example/base/KEY_BG"
OWN = "https://own.example/base/KEY_PREDICT"

# --- 1. своя ручка выигрывает у bg -------------------------------------------------------
assert pick_poll_endpoint(OWN, BG, COMBAT) == (OWN, "свой")

# --- 2. ручки нет -> bg (прежнее поведение, откат мгновенный) ----------------------------
assert pick_poll_endpoint("", BG, COMBAT) == (BG, "bg")
assert pick_poll_endpoint(None, BG, COMBAT) == (BG, "bg")

# --- 3. ничего не задано -> боевой, и он НАЗВАН боевым ----------------------------------
assert pick_poll_endpoint("", "", COMBAT) == (None, "боевой")

# --- 4. ГЛАВНОЕ: ручка, указывающая в БОЕВОЙ ключ, не смеет зваться «свой»/«bg» ----------
# Это и есть дефект «источник врёт»: конфиг, где bg_rpc_url скопирован с боевого, показывал
# бы «узел=bg» при полле, жгущем квоту горячего пути. Отдельного клиента тоже не создаём.
assert pick_poll_endpoint(COMBAT, BG, COMBAT) == (None, "боевой"), \
    "своя ручка = боевой URL, а источник назван не боевым"
assert pick_poll_endpoint("", COMBAT, COMBAT) == (None, "боевой"), \
    "bg = боевой URL, а источник назван bg"

# --- 5. пробелы не делают из пустого значения адрес --------------------------------------
assert pick_poll_endpoint("   ", BG, COMBAT) == (BG, "bg")
assert pick_poll_endpoint("  " + OWN + " ", BG, COMBAT) == (OWN, "свой")

# --- 6. КОНТРОЛЬ: боевой URL пуст (конфиг без него) — своя ручка всё равно берётся --------
assert pick_poll_endpoint(OWN, "", "") == (OWN, "свой")

# --- 7. СТРУКТУРНО: main.py зовёт именно эту функцию, а не свою копию логики -------------
main = pathlib.Path("main.py").read_text()
assert "pick_poll_endpoint(" in main, "main.py не зовёт общий выбор узла"
assert "PREDICT_RPC_URL" in main, "ручка не прокинута из окружения"
# и НЕ печатает сам URL: в нём ключ, и он уже однажды уехал в журнал через str(e).
# Проверять надо СТРОКИ ЛОГИРОВАНИЯ, а не любое вхождение: первая редакция этой проверки
# ловила `cfg.rpc_url)` по хвосту `_url)` и падала на здоровом коде — гард обязан смотреть
# на то же, на что смотрит дефект.
_blk = main[main.index("pick_poll_endpoint("):]
_blk = _blk[:_blk.index("drv = PredictDriver")]
_logs = [l for l in _blk.splitlines() if "log." in l]
assert _logs, "источник узла вообще не пишется в журнал — на чьём ключе полл, знать нужно"
assert any("_src" in l for l in _logs), "в журнал не идёт ИМЯ источника"
for l in _logs:
    assert "_url" not in l, "URL полла печатается в журнал (в нём ключ): %s" % l.strip()

print("OK: полл предиктора берёт свой узел, источник в журнале не врёт (#33)")
