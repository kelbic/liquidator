"""Лимит газа пробы 3M -> 1M: порог немоты втрое ниже, попадание в блок шире (#89).

(1) ПОПАДАНИЕ В РЕШАЮЩИЙ БЛОК. op-geth снимает с пула ПОЛНЫЙ лимит tx, поэтому пробу на 3M не
    пускают всякий раз, когда в блоке осталось меньше 3M газа — а это ровно хвост стопроцентно
    заполненных блоков каскада (49666339-42 шли на 399.58-399.99M из 400M при лимите 400M).
    Это не страховка, а прямое попадание туда, где решается гонка.

(2) ПОРОГ НЕМОТЫ. Резерв гейта патрона считается как gas x maxFee, значит лимит входит в него
    множителем: при 3M флот немел выше 0.083 gwei (замер: 82% ног при 0.0808), при 1M — выше
    0.250 gwei.

Запас ЧЕСТНЫЙ: замеренный худший случай пробы 710k (форк #70), сегодняшний прогон дал 649 623.
НО существующий набор требовал больше — 709 038 (попытка со свопом) + 214 941 (надбавка за копию
плана из стораджа) = 923 979, и это требование старше и консервативнее моего: первая редакция
ставила 900k и упала на нём. Ставим 1 000 000 — покрывает и его, и даёт +41% над 710k. Ниже не опускаем: цена недолёта — проигранная УЖЕ ВЫИГРАННАЯ гонка,
цена перелёта — лишь более высокий порог немоты. Размен несимметричен.

МНОЖИТЕЛЬ maxFee ОСТАВЛЕН 20 ОСОЗНАННО. Соблазн был опустить его до 5 ради порога, но размен
считается в пользу ТЕКУЩЕГО режима: порог сегодня не связывает вовсе (за 30 суток максимум базы
по всем 1 296 000 блокам = 0.0614 gwei), а maxFee лестницы при множителе 5 упал бы до 0.026 —
запас 5x над базой, и обычный всплеск делал бы пробы невключаемыми до пересборки в 28-32с.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import chain.execute as ex                                   # noqa: E402
import chain.spec_fire_live as sfl                           # noqa: E402

WORST_PROBE_GAS = 710_000        # форк-замер #70, верхняя граница исполненной пробы
OBSERVED_TODAY = 649_623         # сегодняшний форк-прогон с Liquidated
FUND, FLOOR = int(0.008e18), int(0.003e18)
BASE_TYPICAL = 5_000_000         # 0.005 gwei — пол Base, типичная база


def mute_threshold(gas, mult, tip):
    """Порог basefee, выше которого нога немеет: bal - gas x (bf x mult + tip) < FLOOR."""
    return ((FUND - FLOOR) / gas - tip) / mult


# --- 1. Лимит покрывает замеренный худший случай с ЧЕСТНЫМ запасом ------------------------
g = sfl.SPEC_FIRE_V2_FIRE_GAS
assert g >= WORST_PROBE_GAS, \
    "лимит %d НИЖЕ замеренного худшего случая %d — победа сгорит по газу" % (g, WORST_PROBE_GAS)
assert g >= WORST_PROBE_GAS * 1.2, "запас над худшим случаем меньше 20%% (%d/%d)" % (g, WORST_PROBE_GAS)
assert g < 3_000_000, "лимит не уменьшен — выигрыш по пулу и порогу не получен"
print("OK 1/4: лимит %d покрывает худшие %d (+%.0f%%) и наблюдённые сегодня %d" % (
    g, WORST_PROBE_GAS, (g / WORST_PROBE_GAS - 1) * 100, OBSERVED_TODAY))

# --- 2. Порог немоты вырос, и это следствие ИМЕННО лимита ---------------------------------
tip = ex._PROBE_TIP_WEI
mult = ex._VOLLEY_PRESIGN_MAXFEE_MULT
_new = mute_threshold(g, mult, tip)
_old = mute_threshold(3_000_000, mult, tip)
assert _new > _old * 3, "порог вырос менее чем втрое (%.4f -> %.4f gwei)" % (_old / 1e9, _new / 1e9)
print("OK 2/4: порог немоты %.4f -> %.4f gwei (в %.1f раза) — только за счёт лимита" % (
    _old / 1e9, _new / 1e9, _new / _old))

# --- 3. КОНТРОЛЬ: запас валидности лестницы НЕ разменян -----------------------------------
# Если бы я опустил множитель ради порога, maxFee лестницы упал бы и пробы стали бы
# невключаемыми на обычном всплеске базы. Это был реальный соблазн — гард его фиксирует.
_maxfee = BASE_TYPICAL * mult + tip
assert mult >= 20, "множитель maxFee опущен — разменяли валидность лестницы на порог, которого " \
                   "сегодня не существует (макс база за 30 суток 0.0614 gwei)"
assert _maxfee >= BASE_TYPICAL * 20, "запас maxFee над базой упал ниже 20x"
print("OK 3/4: КОНТРОЛЬ — maxFee лестницы %.4f gwei, запас %dx над базой (не разменян)" % (
    _maxfee / 1e9, mult))

# --- 4. Пул: выигрыш ОТНОСИТЕЛЬНЫЙ, и утверждать больше замера нельзя ---------------------
# Первая редакция этого пункта утверждала «проба влезает в хвост каскадного блока» — и упала:
# в самом полном из замеренных (49666339-42) остаток всего 420 000, туда не влезает ни 3M, ни
# 1M. Честное утверждение слабее и проверяемо: tx втрое меньше, значит проходит в СТРОГО более
# широком множестве блоков — во всех, где остаток между новым лимитом и прежними 3M.
BLOCK_LIMIT = 400_000_000
CASCADE_USED = 399_580_000       # самый полный из замеренных каскадных блоков
_left = BLOCK_LIMIT - CASCADE_USED
assert g < 3_000_000, "лимит не уменьшен — множество проходимых блоков не расширилось"
assert _left < g, "пример потерял остроту: в самый полный хвост влезает даже новый лимит"
print("OK 4/4: остаток самого полного хвоста %d — не влезает ни 3M, ни %d; выигрыш в том, что "
      "проходимо всё с остатком %d..3M вместо >3M" % (_left, g, g))
print("=== #89 ЗАКРЫТ ===")
