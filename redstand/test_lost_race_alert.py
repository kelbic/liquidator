"""Ш16: проигранная гонка обязана СООБЩАТЬ О СЕБЕ («деньги прошли мимо»).

ЗАМЕР 11.08: за сутки мимо прошло 79 ликвидаций в 9 блоках, включая каскад на $52 320 (наша
доля по оценке самого бота ~$365 чистыми) — и НИ ОДНОГО сообщения владельцу. Потери находились
вручную в журнале постфактум. При этом `_submit_xray` УЖЕ отличал «нас обогнали» (race) от
«позиция была здорова» (not-race): вердикт вычислялся и выбрасывался.

Две защиты, обе из наших же канонов:
  * ПОРОГ ПО ДЕНЬГАМ — «порог для деньги-прошли-мимо = наш собственный пол огня» (31.07);
  * ОКНО АНТИСПАМА — «повтор тревоги по осциллирующей величине только на эскалации» (07.08):
    каскад из 44 ликвидаций не должен дать 44 сообщения.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import chain.execute as ex                                    # noqa: E402


def reset():
    ex._LOST_RACE_MSG = None
    ex._LOST_RACE_TS = 0.0
    ex._LOST_RACE_ACC[0], ex._LOST_RACE_ACC[1] = 0, 0.0


# --- 1. ГЛАВНОЕ: крупная проигранная гонка -> сообщение ----------------------------------
reset()
assert ex.note_lost_race("0xVICTIM", 15594.0, "0xWINNER", 2, win_tip_gwei=0.0016,
                         our_tip_gwei=0.5, now=1000.0) is True
m = ex.pop_lost_race()
assert m and "ДЕНЬГИ МИМО" in m, m
assert "15594" in m and "0xWINNER" in m[:200], m
assert "0.0016" in m and "0.5000" in m, "tip победителя и наш обязаны быть в сообщении"
print("OK 1/6: крупная гонка -> сообщение с долгом, победителем и сравнением tip")

# --- 2. one-shot: второй pop пуст ---------------------------------------------------------
assert ex.pop_lost_race() is None, "сообщение отдаётся дважды — будет дубль в телеграме"
print("OK 2/6: сообщение одноразовое")

# --- 3. ПОРОГ: мелочь НЕ будит ------------------------------------------------------------
# Канон 31.07: порог = наш собственный пол огня, а не число с потолка.
reset()
assert ex.note_lost_race("0xV", ex.LOST_RACE_ALERT_USD - 1, "0xW", 1, now=1000.0) is False
assert ex.pop_lost_race() is None, "потеря ниже порога разбудила владельца"
print("OK 3/6: потеря ниже $%.0f не будит" % ex.LOST_RACE_ALERT_USD)

# --- 4. ОКНО АНТИСПАМА: каскад даёт ОДНО сообщение, а не сорок четыре ---------------------
reset()
sent = 0
for i in range(44):
    if ex.note_lost_race("0xV%d" % i, 1000.0, "0xW", 1, now=1000.0 + i * 0.5):
        sent += 1
assert sent == 1, "каскад из 44 гонок дал %d сообщений — телеграм утонет" % sent
print("OK 4/6: каскад из 44 гонок -> 1 сообщение (окно %.0fс)" % ex.LOST_RACE_WINDOW_SEC)

# --- 5. СЧЁТ НЕ ТЕРЯЕТСЯ: накопленное приезжает следующим сообщением ----------------------
# Иначе антиспам превратился бы в тихую потерю данных.
ex.pop_lost_race()
assert ex.note_lost_race("0xLAST", 2000.0, "0xW", 1,
                         now=1000.0 + ex.LOST_RACE_WINDOW_SEC + 1) is True
m2 = ex.pop_lost_race()
assert "накоплено гонок: 44" in m2, "подавленные гонки потерялись: %s" % m2
assert "45000" in m2 or "45,000" in m2 or "$45000" in m2, m2
print("OK 5/6: подавленные 44 гонки приехали итогом на $45000 — счёт не потерян")

# --- 6. КОНТРОЛЬ: СВОЯ победа сообщением НЕ считается -------------------------------------
# В коде за это отвечает `if not _self`. Проверяем структурно: вызов под гардом self-win.
src = pathlib.Path("chain/execute.py").read_text()
# ВНИМАНИЕ: ищем МЕСТО ВЫЗОВА, а не определение функции — `index` находит `def` первым
# (поймано первым прогоном теста).
i = src.rindex("note_lost_race(borrower")
assert i > src.index("def note_lost_race("), "нашли определение, а не вызов"
win = src[max(0, i - 500):i]
assert "if not _self:" in win, "своя победа шлёт «деньги мимо» — ложная тревога на КАЖДУЮ победу"
print("OK 6/6: КОНТРОЛЬ — своя победа (self-win) сообщением не считается")

# --- СТРУКТУРНО: потребитель заведён, иначе сообщение некому забрать ----------------------
hp = pathlib.Path("chain/hotpath.py").read_text()
assert "pop_lost_race()" in hp, "никто не забирает сообщение — Ш16 мертв по построению"
assert "lost-race" in hp, "нет ключа антифлуда у алертера"
j = hp.index("pop_lost_race()")
assert "alerter.send_async" in hp[j:j + 300], "сообщение забирают, но не отправляют"
print("СТРУКТУРНО: потребитель заведён в hotpath и отправляет с ключом антифлуда")
print("=== Ш16 ЗАКРЫТ: деньги мимо больше не проходят молча ===")
