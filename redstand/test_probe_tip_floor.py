"""Пробы флота идут на ПОЛУ приоритета, боевой путь — нет (#91).

Находка ревьюера 10.08, перепроверена мной прямым перечислением цепи.

Блок Base не плоский FCFS: это склейка суб-блоков (флэшблоки 200мс), и ВНУТРИ каждого порядок
идёт по УБЫВАНИЮ tip. Обновление оракула приходит на ПОЛУ рынка и потому лежит глубоко в хвосте
своего суб-блока — в блоке 49666338 транзит на смещении 270 из 537, все призы на 276..448.
Перечисление позиций 2164..2191 (транзит 2170 и взятые призы 2176/2179/2181/2182/2187): у ВСЕХ
tip ровно 0.001 gwei, ни одной точки роста на 27 подряд позициях.

Значит плата выше пола не помогает, а ДИСКВАЛИФИЦИРУЕТ: сортировка выносит пробу в голову
суб-блока, на сотни позиций РАНЬШЕ транзита, где жертва ещё здорова — отсюда наши сплошные
`position is healthy`. Мы платили 0.05 gwei (50 полов), а в каскаде dynamic_tip_gwei поднимал
до 0.5 (500 полов) — максимум платы ровно там, где призы. В призовом окне [T+1, T+20] у
победителей 8/8/3/1 tx, у нас 0.

Режима ДВА, и они разведены по путям: пробы флота — на полу (садиться в хвост рядом с
транзитом); боевой dispatch с главного кошелька — высокий tip, потому что в суб-блоках зачистки
правило переворачивается (приз на idx 2860 взяла tx с 24.65 gwei, наша проба стояла в том же
суб-блоке на смещении 8 и проиграла по tip). Единая ставка проигрывала в обоих режимах сразу.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import chain.execute as ex                                   # noqa: E402

FLOOR = 1_000_000            # 0.001 gwei — замеренный пол рынка в блоке транзита
COMBAT_TIP_GWEI = 0.05       # то, что несли пробы ДО фикса

# --- 1. Константа проб равна полу и вынесена ВЫШЕ всех использований ---------------------
assert ex._PROBE_TIP_WEI == FLOOR, \
    "tip проб %d wei, а замеренный пол рынка %d" % (ex._PROBE_TIP_WEI, FLOOR)
src = pathlib.Path("chain/execute.py").read_text()
_def = src.index("_PROBE_TIP_WEI = int(os.environ.get(")
_first_use = src.index("_PROBE_TIP_WEI", _def + 10)
assert _def < _first_use, "константа объявлена ПОСЛЕ использования — это NameError в бою"
print("OK 1/5: пол проб = %d wei (0.001 gwei), объявлен выше всех использований" % FLOOR)

# --- 2. Пробы флота больше не наследуют боевой tip ---------------------------------------
# Ш24: лестница берёт ТИР СВОЕЙ НОГИ (probe_tip_for), V1-проба — прежнюю константу.
# Смысл гарда не изменился: пробы не должны наследовать боевой cfg.tip_gwei. Изменилось лишь
# то, что «пол» стал портфелем из четырёх значений класса, а не одним числом (замер 11.08:
# доминирующий класс меняется каждые ~2 секунды, угадать его подписью нельзя).
for fn, want in (("def presign_ladder(", "probe_tip_for(addr)"),
                 ("def send_volley_probe(", "_PROBE_TIP_WEI")):
    i = src.index(fn)
    blk = src[i:src.index("\ndef ", i + 10)]
    assert want in blk, "%s не берёт пол/тир (ждали %s)" % (fn, want)
    assert "int(cfg.tip_gwei * 1e9)" not in blk.split("tip_wei =")[1].split("\n")[0], \
        "%s всё ещё берёт боевой tip по умолчанию" % fn
# и КАЖДЫЙ тир обязан остаться в классе пола, а не уехать в боевые gwei
for t in ex._PROBE_TIP_TIERS:
    assert t <= 10_000_000, "тир %d wei вне класса пола — это уже боевой tip" % t
print("OK 2/5: лестница берёт тир своей ноги, V1 — пол; все тиры в классе пола (%s)"
      % ", ".join(str(t) for t in ex._PROBE_TIP_TIERS))

# --- 3. КОНТРОЛЬ: боевой путь пол НЕ унаследовал ------------------------------------------
# Если бы пол протёк в dispatch, мы проигрывали бы суб-блоки зачистки, где выигрывает высокий
# tip. Это вторая половина двухрежимной политики, и её легко сломать одной глобальной заменой —
# я такую замену уже сделал по ошибке при этой же правке.
from strategy.pnl import lif_from_lltv                       # noqa: E402,F401  (импорт-санити)
import chain.hotpath as hp                                   # noqa: E402

cfg = type("C", (), {"tip_gwei": COMBAT_TIP_GWEI, "tip_step_gwei": 0.5})()
_t = hp.dynamic_tip_gwei(cfg, 10_000.0, now=0.0)
assert _t >= COMBAT_TIP_GWEI, \
    "боевой tip упал до %.6f — пол протёк в dispatch, зачистку будем проигрывать" % _t
assert int(_t * 1e9) > FLOOR, "боевой tip сравнялся с полом — режимы схлопнулись в один"
print("OK 3/5: КОНТРОЛЬ — боевой dispatch остался на %.3f gwei (в %d раз выше пола)" % (
    _t, int(_t * 1e9) // FLOOR))

# --- 4. Пол ниже прежнего значения ровно во столько раз, во сколько мы промахивались -------
_was = int(COMBAT_TIP_GWEI * 1e9)
assert _was // FLOOR == 50, "прежний tip был %d полов — пример разошёлся с замером" % (_was // FLOOR)
# и побочный выигрыш: max_fee лестницы = base*MULT + tip, значит резерв гейта патрона тоже ниже
_base = 5_000_000                                            # 0.005 gwei — типичная база Base
_mf_old = _base * ex._VOLLEY_PRESIGN_MAXFEE_MULT + _was
_mf_new = _base * ex._VOLLEY_PRESIGN_MAXFEE_MULT + FLOOR
assert _mf_new < _mf_old, "max_fee не снизился — побочный эффект потерян"
print("OK 4/5: было 50 полов -> стало 1; max_fee лестницы %d -> %d wei (резерв патрона ниже)" % (
    _mf_old, _mf_new))
# --- 5. Аудит лестниц меряет ТЕМ ЖЕ tip, которым подписано --------------------------------
# Иначе все ноги разом выглядят протухшими и уходят в вечную пересборку (110 подписей по кругу).
# Эту регрессию поймал существующий тест при первой редакции фикса — гард закрепляет связку.
sfl_src = pathlib.Path("chain/spec_fire_live.py").read_text()
# Ш24b: решение о пересборке уехало в чистую execute.plan_ladder_resigns (её экзаменует
# test_probe_tip_tiers.py), но ВХОД у неё прежний — тир ЭТОЙ ноги. Якорь на него.
_a = sfl_src.index("plan_ladder_resigns")
# окно берём ПО ОБЕ СТОРОНЫ вызова: тир стоит аргументом ВНУТРИ самого вызова, а не строкой выше.
_win = sfl_src[max(0, _a - 900):_a + 300]
# Ш24: связка та же, но tip стал ПЕР-НОГОВЫМ. Аудит обязан сверять лестницу с тиром ЭТОЙ
# ноги: общая константа объявила бы протухшими три тира из четырёх и загнала флот в вечную
# пересборку — то есть тиры убили бы сами себя.
assert "_ex.probe_tip_for" in _win, "аудит лестниц сверяется не с тиром СВОЕЙ ноги"
assert 'getattr(self.cfg, "tip_gwei"' not in _win, "боевой tip вернулся в аудит лестниц"
# ...и пер-ноговость обязана дожить до самой сверки: планировщик зовёт tip_of на КАЖДУЮ ногу
_pl = pathlib.Path("chain/execute.py").read_text()
_pl = _pl[_pl.index("def plan_ladder_resigns("):]
_pl = _pl[:_pl.index("\ndef ", 10)]
assert "tip_of(a)" in _pl, "планировщик пересборки мерит флот ОДНОЙ ценой — вечная пересборка"
print("OK 5/5: аудит сверяет каждую ногу с ЕЁ тиром — вечной пересборки не будет")

print("=== #91 ЗАКРЫТ (приёмка боем: наши пробы в окне [T+1, T+20] на полу) ===")
