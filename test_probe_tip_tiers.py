"""Ш24: тиры tip по флоту вместо одной константы.

ЗАМЕР 11.08 (5407 блоков за 3 часа, analysis/tip_floor_watch.py). Доминирующий класс блока —
он же tip транзита и всего призового окна — МЕНЯЕТСЯ между соседними блоками в 33% случаев,
медианная длина серии ОДИН блок = две секунды. Лестницы подписываются за секунды-минуты до
огня, поэтому «подписать по свежему замеру» не успеет никогда.

Частоты: 1 000 000 — 63.8%, 1 100 000 — 13.0%, 1 775 000 — 7.0%. Три уровня покрывают 83.8%
блоков, четыре — 87.1%. Четвёртый (3 000 000) взят не из частот, а из единственного каскада
11.08 06:38 — стоит СТРАХОВКОЙ, потому что каскад поднимает загрузку, и именно там деньги.

ПОЧЕМУ НЕ ПРОСТО ПОДНЯТЬ КОНСТАНТУ (вопрос kelbic). Замер: с 1 000 000 мы ниже класса в 56%
блоков (хвост), с 3 000 000 были бы ВЫШЕ класса в 99.9% (голова, ДО транзита, где цена ещё
старая — дефект #91). Единая тройка не лечит, а переворачивает промах и делает его почти
стопроцентным.
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from collections import Counter                            # noqa: E402

import chain.execute as ex                                 # noqa: E402
import chain.fire_engine as fe                             # noqa: E402

FLEET = ["0x" + hashlib.sha256(str(i).encode()).hexdigest()[:40] for i in range(110)]

# --- 1. ГЛАВНОЕ: флот делится на тиры, и каждый тир населён ------------------------------
c = Counter(ex.probe_tip_for(a) for a in FLEET)
assert set(c) == set(ex._PROBE_TIP_TIERS), "не все тиры населены: %s" % dict(c)
lo, hi = min(c.values()), max(c.values())
ideal = len(FLEET) / len(ex._PROBE_TIP_TIERS)
assert lo >= ideal * 0.6, "тир голодает (%d при идеале %.0f) — в классе окажется мало проб" % (lo, ideal)
print("OK 1/6: 110 ног -> %s (идеал %.0f на тир)" % (dict(sorted(c.items())), ideal))

# --- 2. Назначение ДЕТЕРМИНИРОВАННО: та же нога — тот же тир, всегда ----------------------
# Иначе лестница подписана одним tip, а аудит сверял бы её с другим — вечная пересборка.
for a in FLEET[:20]:
    assert ex.probe_tip_for(a) == ex.probe_tip_for(a) == ex.probe_tip_for(a.lower())
print("OK 2/6: тир ноги детерминирован (иначе аудит гонял бы вечную пересборку)")

# --- 3. Каскадный тир ПРИСУТСТВУЕТ ------------------------------------------------------
# Он не из частот, а страховка: в блоках 49820471/49820472 (30 ликвидаций) класс был 3 000 000,
# и без этого тира мы были бы в хвосте ровно там, где деньги.
assert 3_000_000 in ex._PROBE_TIP_TIERS, "нет каскадного тира — в каскаде снова хвост"
assert 1_000_000 in ex._PROBE_TIP_TIERS, "нет тира на самый частый класс (63.8% блоков)"
print("OK 3/6: каскадный тир 3e6 и массовый 1e6 оба на месте")

# --- 4. Лестница подписывается ТИРОМ СВОЕЙ НОГИ, а не общей константой -------------------
src = pathlib.Path("chain/execute.py").read_text()
i = src.index("def presign_ladder(")
blk = src[i:src.index("\ndef ", i + 10)]
assert "probe_tip_for(addr)" in blk, "лестница подписывается общей константой — тиры мертвы"
print("OK 4/6: presign_ladder берёт тир СВОЕЙ ноги")

# --- 5. Аудит цены сверяет лестницу с ЕЁ ЖЕ тиром ----------------------------------------
# Если бы аудит мерил весь флот одной величиной, три тира из четырёх он объявил бы протухшими
# и загнал флот в вечную пересборку — то есть тиры убили бы сами себя.
sfl = pathlib.Path("chain/spec_fire_live.py").read_text()
j = sfl.index("def _audit(addrs):")
ablk = sfl[j:sfl.index("def _combat_url()", j)]
assert "probe_tip_for(a)" in ablk, "аудит мерит флот ОДНОЙ ценой — вечная пересборка"
assert "_PROBE_TIP_WEI" not in ablk, "в аудите осталась общая константа"
print("OK 5/6: аудит сверяет каждую ногу с ЕЁ тиром (иначе вечная пересборка)")

# --- 6. Плотность: попавший тир обязан давать ~8 проб на блок ----------------------------
# У победителей в призовом окне было 8, 8, 3 и 1. При четырёх тирах в классе ~1/4 флота,
# значит общий темп обязан дать 4× от нужного.
per_block = fe.ENGINE_HOLD_RATE * 2.0                      # блок Base = 2с
in_class = per_block / len(ex._PROBE_TIP_TIERS)
assert in_class >= 7.0, "в классе %.1f проб на блок — меньше, чем было у победителей" % in_class
print("OK 6/6: темп %.0f/с -> %.0f проб на блок, из них %.1f в классе (у победителей 8)"
      % (fe.ENGINE_HOLD_RATE, per_block, in_class))

# --- КОНТРОЛЬ: откат одной переменной ----------------------------------------------------
_saved = ex._PROBE_TIP_TIERS
try:
    ex._PROBE_TIP_TIERS = ()
    assert ex.probe_tip_for(FLEET[0]) == ex._PROBE_TIP_WEI, "пустой список тиров не возвращает прежнее поведение"
finally:
    ex._PROBE_TIP_TIERS = _saved
print("КОНТРОЛЬ: SPEC_FIRE_PROBE_TIP_TIERS= (пусто) -> прежняя константа, откат без правки кода")
print("=== Ш24 ЗАКРЫТ: портфель тиров вместо угадывания величины, живущей 2 секунды ===")
