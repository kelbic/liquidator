"""27.08 ДОСЯГАЕМОСТЬ: доска берёт цель, которая может флипнуть, а не самую жирную.

Вскрытие каскада 26.08 15:05 (блок 50483683). Состояние на 50483682:
  НАША ЦЕЛЬ 0x649f8d8e  HF 1.02319 (2.27% от кромки), долг $174 365
  победитель 0xba93e7d9 HF 1.00096 (0.096%),           долг $20 430 -> погашено $19 408
  ещё девять победителей — HF 1.00021…1.00509
Замер 920 подтверждённых пушей за 3 суток: МАКСИМУМ толчка 0.601%, p99 0.510%; пер-фид
BTC p99 0.192%, XRP p99 0.601% (разброс втрое). Цель на 2.27% не флипает ни при одном
наблюдавшемся толчке — 7 391 проба за 9.8 суток, все «position is healthy», 0 исполнений.
Гейт стоял на 3% — в пять раз шире максимального толчка, ранг был «чист по долгу».
"""
import sys, time
sys.path.insert(0, ".")
import chain.push_scale as ps

# --- 1. ПОЗИТИВНЫЙ КОНТРОЛЬ: механизм вообще отвечает, и семя = замер, а не 3% -----------
ps._RINGS.clear()
r_xrp, r_btc = ps.reach("XRP"), ps.reach("BTC")
assert r_xrp is not None and r_btc is not None, "механизм молчит — дальше ноль ничего не значит"
assert abs(r_xrp - 0.00601) < 1e-9 and abs(r_btc - 0.00226) < 1e-9, (r_xrp, r_btc)
assert r_xrp > r_btc * 2, "пер-фид обязан различать: XRP втрое шире BTC, общий порог неверен обоим"
print("UNIT_OK 1: семя из замера — XRP %.4f%% против BTC %.4f%% (общий порог был бы неверен обоим)"
      % (r_xrp * 100, r_btc * 100))

# --- 2. ГЛАВНОЕ: цель каскада отсекается, победитель проходит ----------------------------
D_OURS, D_WIN = 0.02266, 0.00096          # 1 - 1/1.02319 и 1 - 1/1.00096
assert D_OURS > r_xrp, "цель 2.27%% обязана быть ВНЕ досягаемости (гейт %.4f%%)" % (r_xrp * 100)
assert D_WIN < r_xrp, "победитель 0.096%% обязан быть ВНУТРИ"
assert ps.p_flip("XRP", D_OURS) == 0.0, "вес недосягаемой цели обязан быть НОЛЬ"
assert ps.p_flip("XRP", D_WIN) > 0.0, "вес досягаемой цели обязан быть > 0"
# ранг по ожиданию переставляет их местами, ранг по долгу — нет
ours, win = 174365.0, 20430.0
assert ours > win, "исходные данные каскада: наша цель БОЛЬШЕ по долгу"
assert ours * ps.p_flip("XRP", D_OURS) < win * ps.p_flip("XRP", D_WIN), \
    "ранг по ожиданию обязан поставить победителя ВПЕРЕДИ жирной недосягаемой цели"
print("UNIT_OK 2: ожидание $%.0f (наша, вес %.2f) < $%.0f (победитель, вес %.2f) — порядок исправлен"
      % (ours * ps.p_flip("XRP", D_OURS), ps.p_flip("XRP", D_OURS),
         win * ps.p_flip("XRP", D_WIN), ps.p_flip("XRP", D_WIN)))

# --- 3. ЖИВОЙ ЗАМЕР ВЫТЕСНЯЕТ СЕМЯ ------------------------------------------------------
ps._RINGS.clear()
now = time.time()
for i in range(ps.MIN_N + 5):
    ps.note_push("XRP", 0.10, now=now - i)             # фид стал спокойнее семени
assert ps.samples("XRP") >= ps.MIN_N
assert abs(ps.reach("XRP") - 0.0010) < 1e-9, ps.reach("XRP")
assert ps.p_flip("XRP", 0.0005) == 1.0 and ps.p_flip("XRP", 0.002) == 0.0
print("UNIT_OK 3: живой замер вытеснил семя — reach 0.601%% -> %.4f%%" % (ps.reach("XRP") * 100))

# --- 4. НЕЗНАНИЕ НЕ ОТКРЫВАЕТ ГЕЙТ ШИРЕ -------------------------------------------------
ps._RINGS.clear()
unknown = ps.reach("НЕТ-ТАКОГО-ФИДА")
assert unknown is not None and abs(unknown - 0.00601) < 1e-9, unknown
assert unknown < 0.03, "незнание обязано давать ЗАМЕРЕННЫЙ запас поля, а не прежние 3%"
print("UNIT_OK 4: неизвестный фид -> максимум поля 0.601%%, а не 3%% (незнание не щедрость)")

# --- 5. ОТКАТ ОДНОЙ ПЕРЕМЕННОЙ ----------------------------------------------------------
ps.PUSH_SCALE_ON = False
assert ps.reach("XRP") is None, "PUSH_SCALE=0 обязан отдать None — вызывающий вернётся к константе"
ps.PUSH_SCALE_ON = True
print("UNIT_OK 5: PUSH_SCALE=0 -> None -> прежняя константа бит-в-бит")

# --- 6. ПРОВОДКА: гейт и ранг ДЕЙСТВИТЕЛЬНО стоят в боевом пути --------------------------
src = open("chain/spec_fire_live.py").read()
assert "_push_scale.reach(feed)" in src, "гейт досягаемости не подключён к арму"
assert "_push_scale.p_flip(feed, _d)" in src, "ранг по ожиданию не подключён к _top_fat"
assert "elig.sort(key=_ev_key)" in src, "ранг всё ещё чист по долгу"
pred = open("chain/predict.py").read()
i = pred.index('elif ev["event"] == "confirmed"')
assert "note_push" in pred[i:i + 700], "масштаб толчка ничем не кормится — кольцо останется пустым"
print("UNIT_OK 6: проводка на месте — гейт, ранг и кормление кольца")
print("=== ДОСЯГАЕМОСТЬ: 6/6 ===")
