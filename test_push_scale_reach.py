"""27.08 РАНГ ПО ОЖИДАНИЮ: доска предпочитает цель, которая МОЖЕТ флипнуть, а не самую жирную.

Вскрытие каскада 26.08 15:05 (блок 50483683), состояние на 50483682:
  НАША ЦЕЛЬ 0x649f8d8e  HF 1.02319 = 2.27% от кромки, долг $174 365
  победитель 0xba93e7d9 HF 1.00096 = 0.096%,           долг $20 430 -> погашено $19 408
  ещё девять победителей — HF 1.00021…1.00509 (все в пределах 0.51%).

ЗАМЕР ПОЛЕМ `ret_pct` (7 суток, n=3150 подтверждённых пушей; ПЕРВЫЙ замер был сделан НЕ ТЕМ
полем — жадный регексп `.*ret_pct=` захватывал `arm_ret_pct`, и числа разошлись в 2.3-5.4 раза):
  XRP p50 0.594% p90 0.970% p99 2.772% | BTC p99 0.530% | ВСЕ p99 1.820% max 6.738%
Цель на 2.27% перекрывают 2.1% пушей XRP — РЕДКО, но не «никогда»: прежнее утверждение
«не флипает ни при одном толчке» ложно и снято. Ранг по ожиданию чинит каскад и без гейта:
$174 365 x 0.021 = $3 662 против $20 430 x 1.00 = $20 430.

ГЕЙТ ДОСЯГАЕМОСТИ СНЯТ отдельно (линза): арм судит состояние за 45-159с до приза, цель приходит
к кромке дрейфом МНОЖЕСТВА толчков; на ретро-примерке 203 ликвидаций вне такого гейта оказались
бы 47.9% победителей. Односкачковую досягаемость меряет FIRE-гейт ниже по пути.
"""
import sys, time
sys.path.insert(0, ".")
import chain.push_scale as ps

ps.STATE_PATH = "/tmp/push_scale_test_state.json"

# --- 1. ПОЗИТИВНЫЙ КОНТРОЛЬ: механизм отвечает и различает фиды -------------------------
ps._RINGS.clear()
assert abs(ps.reach("XRP") - 0.02772) < 1e-9 and abs(ps.reach("BTC") - 0.00530) < 1e-9, \
    (ps.reach("XRP"), ps.reach("BTC"))
assert ps.reach("XRP") > ps.reach("BTC") * 4, "пер-фид обязан различать: XRP впятеро шире BTC"
print("UNIT_OK 1: семя ПРАВИЛЬНОГО поля — XRP %.3f%% против BTC %.3f%%" % (ps.reach("XRP") * 100, ps.reach("BTC") * 100))

# --- 2. БЕЗ ЗАМЕРА p_flip НЕ СУДИТ ------------------------------------------------------
# Прежняя редакция отдавала ступень 1.0/0.0 от семени: всё за семенем получало РОВНО 0.0,
# ключи ранга становились равны, и устойчивая сортировка отдавала top-1 по порядку вставки.
assert ps.p_flip("XRP", 0.0227) is None and ps.p_flip("XRP", 0.0001) is None
print("UNIT_OK 2: без MIN_N замеров p_flip = None (ранг обязан деградировать к долгу)")

# --- 3. ГЛАВНОЕ: на живом кольце ожидание переставляет каскад ----------------------------
ps._RINGS.clear()
now = time.time()
# кольцо XRP по замеру: p50 0.594%, хвост до 2.772%
for i, v in enumerate([0.59] * 90 + [2.80] * 2 + [1.20] * 8):
    ps.note_push("XRP", v, now=now - i)
D_OURS, D_WIN = 0.02266, 0.00096
w_ours, w_win = ps.p_flip("XRP", D_OURS), ps.p_flip("XRP", D_WIN)
assert 0.0 < w_ours < 0.05, ("вес цели на 2.27%% обязан быть малым, но НЕ нулём", w_ours)
assert w_win > 0.9, w_win
ours, win = 174365.0, 20430.0
assert ours > win, "исходные данные каскада: наша цель БОЛЬШЕ по долгу"
assert ours * w_ours < win * w_win, "ранг по ожиданию обязан поставить победителя впереди"
print("UNIT_OK 3: ожидание $%.0f (наша, вес %.3f) < $%.0f (победитель, вес %.3f)"
      % (ours * w_ours, w_ours, win * w_win, w_win))

# --- 4. ПЕРСИСТЕНТНОСТЬ: кольцо переживает рестарт --------------------------------------
# 63 старта юнита за 10 суток, аптайм ~3.8ч; MIN_N=20 набирается за 3.8-17.5ч по фидам.
# Без диска живой замер не включается НИКОГДА, и механизм навсегда остаётся на семени.
n_saved = ps.save()
assert n_saved == 100, n_saved
ps._RINGS.clear()
assert ps.samples("XRP") == 0 and ps.p_flip("XRP", D_WIN) is None
assert ps.load() == 100 and ps.samples("XRP") == 100
assert abs(ps.p_flip("XRP", D_WIN) - w_win) < 1e-12, "после подъёма вес обязан совпасть"
print("UNIT_OK 4: кольцо пережило рестарт (save/load %d замеров, вес совпал)" % n_saved)

# --- 5. МУСОР НЕ ПИННИТ КВАНТИЛЬ --------------------------------------------------------
ps._RINGS.clear()
for i in range(30):
    ps.note_push("BTC", 0.15, now=now - i)
assert ps.note_push("BTC", 40.0) is False, "выброс 40%% обязан быть отброшен как мусор"
assert abs(ps.reach("BTC") - 0.0015) < 1e-9, ps.reach("BTC")
print("UNIT_OK 5: выброс 40%% отброшен (порог MAX_SANE_PCT=%.0f%%), квантиль не запиннен" % ps.MAX_SANE_PCT)

# --- 6. ОТКАТ ---------------------------------------------------------------------------
ps.PUSH_SCALE_ON = False
assert ps.reach("XRP") is None
ps.PUSH_SCALE_ON = True
print("UNIT_OK 6: PUSH_SCALE=0 -> None -> прежнее поведение")

# --- 7. ПРОВОДКА: ранг подключён, ГЕЙТ СНЯТ ---------------------------------------------
src = open("chain/spec_fire_live.py").read()
assert "_push_scale.p_flip(feed, _d)" in src, "ранг по ожиданию не подключён"
assert "elig.sort(key=_ev_key)" in src, "ранг всё ещё чист по долгу"
assert "-(float(t[2]) * _w), -float(t[2])" in src, \
    "нет вторичного ключа по долгу — при равных весах top-1 уедет в порядок вставки"
assert "min(SPEC_FIRE_ARM_MAX_DIST" not in src, \
    "гейт досягаемости обязан быть СНЯТ: он режет 47.9%% реальных победителей"
pred = open("chain/predict.py").read()
i = pred.index('elif ev["event"] == "confirmed"')
assert "note_push" in pred[i:i + 900] and "_ps.save()" in pred[i:i + 900], \
    "кольцо не кормится либо не сохраняется"
print("UNIT_OK 7: ранг и кормление на месте, гейт досягаемости снят")
print("=== РАНГ ПО ОЖИДАНИЮ: 7/7 ===")
