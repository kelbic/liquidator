def _line_epoch(line):
    """Секунды эпохи из ISO-штампа строки; None — если штампа нет (парс не обязан падать)."""
    m = _ISO.search(line)
    if not m:
        return None
    try:
        return time.mktime((int(m.group(1)), int(m.group(2)), int(m.group(3)),
                            int(m.group(4)), int(m.group(5)), int(m.group(6)), 0, 1, -1))
    except (ValueError, OverflowError):
        return None


def _window_sec(cu, proj_m):
    """Длительность окна — ИЗ САМОЙ СТРОКИ: она называет и сколько CU, и с каким темпом.
    cu / (proj CU/s) = секунды. Захардкоженный каденс был бы лишним допущением: уедет
    CU_ROLL/каденс бота — интеграл поедет молча. Фолбэк только когда проекция нулевая."""
    rate = float(proj_m) * 1e6 / SEC_MONTH
    if rate <= 0 or cu <= 0:
        return WINDOW_SEC_FALLBACK
    return cu / rate


def parse_cu_windows(journal_text, *, since_epoch=None):
    """host -> {"projs": [проекции НЕ-бут окон], "boot": сколько бут-окон выкинуто,
    "top": последняя атрибуция, "cu": ВСЕ потраченные CU (вкл. бут), "cu_boot": из них
    бутовые, "sec": покрытое этими окнами время, "n_all": окон всего, "last": макс. эпоха}.
    Только квотуемые хосты (alchemy). Бут-окно = ДВЕ координаты из самой строки: скольз-спан
    < 16 мин (процесс молод) И прогревный топ-потребитель (_BOOT_TOPS). Одной молодости
    мало — 26.08 она красила бутом боевой огонь на многорестартном часе (репро 15:07).

    "projs"/"boot" — для ДИАГНОСТИКИ ВСПЛЕСКА (ex-boot, как было). "cu"/"sec" — для ПРИГОВОРА
    ПО КВОТЕ: провайдер списывает и бут тоже, поэтому в интеграл он входит.

    since_epoch: окна со штампом <= него пропускаются. Прогоны берут 70 минут при каденсе
    в час, то есть ~10 минут КАЖДОГО прогона уже посчитаны предыдущим; без отсечки хвост
    двоил бы эти окна. Строки без разбираемого штампа отсечке не подлежат (не молчим о них:
    парс не обязан падать от смены формата journald)."""
    out = {}
    for line in journal_text.splitlines():
        m = _LINE.search(line)
        if not m:
            continue
        host, cu, proj = m.group(1), int(m.group(2)), float(m.group(3))
        span_min, top = int(m.group(4)), m.group(5).strip()
        if "alchemy" not in host:
            continue
        ep = _line_epoch(line)
        if since_epoch is not None and ep is not None and ep <= since_epoch:
            continue
        d = out.setdefault(host, {"projs": [], "boot": 0, "top": "", "cu": 0, "cu_boot": 0,
                                  "sec": 0.0, "n_all": 0, "last": None})
        d["cu"] += cu
        d["sec"] += _window_sec(cu, proj)
        d["n_all"] += 1
        if ep is not None:
            d["last"] = ep if d["last"] is None else max(d["last"], ep)
        # Бут = ДВЕ координаты (см. _BOOT_TOPS): молодой спан И прогревный топ-потребитель.
        # Молодость одна давала ложь в сторону успокоения на многорестартных часах; топ
        # один не годится тоже — прогревный потребитель на зрелом спане это фон, не бут.
        if span_min < BOOT_SPAN_MIN and _BOOT_TOPS.search(top or ""):
            d["boot"] += 1
            d["cu_boot"] += cu
        else:
            d["projs"].append(proj)
        d["top"] = top or d["top"]
    return out


def count_restarts(journal_text):
    """Сколько РАЗНЫХ процессов бота видно в куске журнала. Рестарт — первоклассный член
    расхода (каждый бут гонит presign_ladder/_pending_nonce/volley_bal_warm), поэтому едет
    в текст тревоги: без него «жжёт много» не отличить от «сегодня много деплоили»."""
    return len({m.group(1) for m in (_PID.search(x) for x in journal_text.splitlines()) if m})


def verdicts(per_host, *, threshold, min_windows):
    """[(host, mean, n_windows, top)] — только хосты, где СРЕДНЕЕ не-бут окон >= порога.
    Квота жжётся суммой => среднее; бут-окна уже выкинуты парсом по полю скольз-спана."""
    out = []
    for host, d in sorted(per_host.items()):
        n = len(d["projs"])
        if n < min_windows:
            continue
        avg = statistics.fmean(d["projs"])
        if avg >= threshold:
            out.append((host, avg, n, d["top"]))
    return out


def load_history(path=None, *, keep_sec=None, now=None):
    """Список записей истории, свежее keep_sec. Битые строки пропускаются молча — история
    вспомогательна, её порча не должна ослеплять сторож (слепота — отдельная ветка)."""
    path = path or HISTORY_PATH
    now = float(now if now is not None else time.time())
    keep_sec = float(keep_sec if keep_sec is not None else 168 * 3600)
    out = []
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                if isinstance(r, dict) and now - float(r.get("ts", 0)) <= keep_sec:
                    out.append(r)
    except OSError:
        return []
    return out


def append_history(rec, path=None, *, keep_sec=None, now=None):
    """Дописать прогон и подрезать хвост. Пишем через чтение-в-память (канон
    file-write-truncates: open(w) усекает ДО чтения)."""
    path = path or HISTORY_PATH
    recs = load_history(path, keep_sec=keep_sec, now=now)
    recs.append(rec)
    data = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in recs)
    try:
        with open(path, "w", encoding="utf-8") as f:
            f.write(data)
    except OSError:
        pass
    return recs


def history_cutoff(recs):
    """Верхняя граница уже посчитанного (максимум по "until"). Отсекает перекрытие прогонов."""
    tops = [float(r["until"]) for r in recs if r.get("until") is not None]
    return max(tops) if tops else None


def quota_verdicts(recs, *, threshold, trail_sec, min_trail_sec, now=None, parked=None):
    """ПРИГОВОР ПО КВОТЕ — интеграл, а не мгновенный темп.

    [(host, rate_M, covered_sec, cu_total)] по хвосту trail_sec: сумма ВСЕХ потраченных CU
    (вкл. бут) делить на покрытое время. Пока покрыто меньше min_trail_sec — НЕ СУДИМ ВОВСЕ
    (возвращаем пусто): огрызок в час и был причиной ложных тревог. Это ровно тот случай,
    когда незнание обязано закрывать гард, а не разрешать выстрел.

    НАЗВАННЫЙ ПРЕДЕЛ (чтобы не читался как месячный факт): знаменатель — время, КОГДА БОТ
    РАБОТАЛ, а не стенные часы. Простой между рестартами в него не входит, поэтому на
    рестарто-обильных сутках оценка выше «стенной» на скважность (20.08: 30.0M против 28.4M,
    ~8% при 5 рестартах за 6ч). Выбрано намеренно и в эту сторону: (а) стенной знаменатель
    считал бы burn-free временем и ПРОПУЩЕННЫЕ прогоны сторожа, то есть занижал бы тем
    сильнее, чем хуже работает сам сторож — недопустимая обратная связь; (б) у гарда квоты
    ошибка в сторону раннего звонка дешевле. Рестарты едут в текст тревоги, чтобы разбирающий
    видел скважность сразу, а не переоткрывал её.
    """
    now = float(now if now is not None else time.time())
    agg = {}
    for r in recs:
        if now - float(r.get("ts", 0)) > trail_sec:
            continue
        for host, d in (r.get("hosts") or {}).items():
            a = agg.setdefault(host, {"cu": 0.0, "sec": 0.0})
            a["cu"] += float(d.get("cu", 0))
            a["sec"] += float(d.get("sec", 0))
    out = []
    parked = set(parked or ())
    for host, a in sorted(agg.items()):
        if a["sec"] < min_trail_sec:
            continue
        if host in parked:
            # Тот же co-наблюдательный замер, что и в ветке остатка: 21.08-22.08 сторож
            # объявлял «#5735 жжёт 31.6M CU/мес» по ключу, по которому бот не сделал ни
            # одного вызова четыре часа. Порог этой правкой НЕ трогается (он защищён
            # замером 22% ложных) — из-под него убирается ключ, расход которого ЗАМЕРЕН
            # нулём, а не оценён хвостом.
            continue
        rate = a["cu"] / a["sec"] * SEC_MONTH / 1e6
        if rate >= threshold:
            out.append((host, rate, a["sec"], a["cu"]))
    return out


def trail_summary(recs, *, trail_sec, now=None):
    """host -> (rate_M, covered_sec, since) по хвосту, БЕЗ порога — для строки штиля и остатка.

    ТРЕТЬЕ ПОЛЕ ДОБАВЛЕНО 22.08 (разбор ложной тревоги по #5735) И ЭТО НЕ УДОБСТВО, А ГАРД.
    covered_sec — сумма РАЗОБРАННОГО времени, величина СКВАЖНОСТНАЯ: у ключа с дырами в
    журнале она усыхает, оставаясь при этом размазанной по всему 24-часовому окну. Ветка
    остатка проверяла «хвост целиком после якоря» выражением (now - covered_sec) >= as_of,
    то есть ЧИТАЛА ПОКРЫТИЕ КАК СТЕННУЮ КООРДИНАТУ. Для #5735 22.08 07:07 покрытие сжалось
    до 11.8ч (ключ молчал 9 часов), проверка дала «начало 21.08 18:59» против якоря 18:53 и
    объявила хвост чистым — при том что окно на деле доставало до 21.08 08:07, на 11 часов
    ДО якоря. 85% CU этого «чистого» хвоста сожжены конфигурацией, уведённой манёвром 18:53.
    Стенное начало окна нельзя вывести из покрытия — его надо ВЕРНУТЬ, что и делает since
    (тем же способом, каким его давно возвращает fresh_summary: until минус покрытие).

    NB: знаменатель ставки остаётся ПОКРЫТИЕМ — это намеренно и защищено замером (см.
    quota_verdicts). Дефект был не в знаменателе, а в его переиспользовании как координаты.
    """
    now = float(now if now is not None else time.time())
    agg = {}
    for r in recs:
        if now - float(r.get("ts", 0)) > trail_sec:
            continue
        until = float(r.get("until") or r.get("ts") or 0)
        for host, d in (r.get("hosts") or {}).items():
            sec = float(d.get("sec", 0))
            a = agg.setdefault(host, [0.0, 0.0, None])
            a[0] += float(d.get("cu", 0))
            a[1] += sec
            start = until - sec
            a[2] = start if a[2] is None else min(a[2], start)
    return {h: ((cu / sec * SEC_MONTH / 1e6) if sec > 0 else 0.0, sec, since)
            for h, (cu, sec, since) in agg.items()}


def fresh_summary(recs, *, n=None, now=None, min_sec=None, max_n=None, as_of_map=None):
    """host -> (cu_per_day, покрытые_секунды, начало_окна, взято_прогонов) по последним записям.

    ЗАЧЕМ ОТДЕЛЬНАЯ ВЕЛИЧИНА (ПРЕДЕЛ 4, разбор тревоги 21.08 23:07). Хвост 24ч — это
    ИНТЕГРАЛ, и он размазывает СТУПЕНЬ. 21.08 в 22:00Z вечерняя кампания подняла #94bf с
    54k до 188k CU/час; хвост 21.6ч показал 30.2M/мес, а последний полный час — 140.6M/мес,
    в 4.7 раза выше. Прецедент 20.08 был ЗЕРКАЛЬНЫМ (хвост завышал, описывая состав
    потребителей, которого уже нет), и лечился отбрасыванием грязного хвоста — но лечение
    молча предполагало, что ошибка бывает только в одну сторону. Она бывает в обе.

    Величина НЕ идёт в приговор по ТЕМПУ (он защищён замером 22% ложных на норме и не
    трогается) — только в ветку ОСТАТКА, где она и связывает: ведро опустошается тем, что
    льётся СЕЙЧАС, а не средним за сутки.

    "начало_окна" — оценка (until минус покрытые секунды): по ней вызывающий проверяет, что
    свежее окно не залезает за якорь, то есть не описывает конфигурацию до манёвра.
    """
    n = int(n if n is not None else FRESH_N)
    min_sec = float(min_sec if min_sec is not None else FRESH_MIN_SEC)
    max_n = max(n, int(max_n if max_n is not None else FRESH_MAX_N))
    as_of_map = as_of_map or {}
    rs = sorted([r for r in recs if r.get("ts") is not None], key=lambda r: float(r["ts"]))

    def _agg(host, k):
        cu = sec = 0.0
        cu_boot = 0.0
        n_sub = n_boot = 0
        since = None
        for r in rs[-k:]:
            d = (r.get("hosts") or {}).get(host)
            if not d:
                continue
            s = float(d.get("sec", 0))
            cu += float(d.get("cu", 0))
            cu_boot += float(d.get("cu_boot", 0) or 0)
            n_sub += int(d.get("n", 0) or 0)
            n_boot += int(d.get("boot", 0) or 0)
            sec += s
            start = float(r.get("until") or r.get("ts") or 0) - s
            since = start if since is None else min(since, start)
        return cu, sec, since, cu_boot, n_sub, n_boot

    hosts = set()
    for r in rs[-max_n:]:
        hosts.update((r.get("hosts") or {}).keys())

    out = {}
    for host in hosts:
        as_of = as_of_map.get(host)
        best = None
        for k in range(n, max_n + 1):
            cu, sec, since, cu_boot, n_sub, n_boot = _agg(host, k)
            if best is not None and as_of is not None and since is not None and since < float(as_of):
                # РОСТ ЗАЛЕЗ ЗА ЯКОРЬ: дальше окно описывало бы конфигурацию до манёвра —
                # ровно тот дефект, ради которого свежее окно и заводилось. Берём последнее
                # чистое. Базовое окно (k=n) не отбрасываем здесь: его чистоту проверяет
                # balance_verdicts тем же сравнением, и снятие проверки обязано краснеть там.
                break
            best = (cu, sec, since, k, cu_boot, n_sub, n_boot)
            if sec >= min_sec:
                break
        if best is None:
            continue
        cu, sec, since, k, cu_boot, n_sub, n_boot = best
        out[host] = ((cu / sec * 86400.0) if sec > 0 else 0.0, sec, since, k,
                     cu_boot, n_sub, n_boot)
    return out



def parked_hosts(recs, candidates, *, n=None):
    """Ключи из `candidates`, по которым бот ПОЛОЖИТЕЛЬНО не ходит. Возвращает множество.

    ЗАЧЕМ (22.08, разбор своей же ложной тревоги по #5735). 21.08 18:53 потребители были
    уведены с #5735, трафика по нему с 18:58 НЕТ ВОВСЕ — а сторож продолжал звонить «остатка
    на 4.0 суток» раз в 6ч, потому что судил ключ ГРЯЗНЫМ ХВОСТОМ, захватившим время до
    манёвра. Прошлая сессия предел назвала и чинить отказалась с обоснованием: «отличить
    "ключ не жжёт" от "сторож ослеп" ОДНОЙ СТРОКОЙ нельзя». Обоснование верное ровно для
    одной строки — и неверное для ПРОГОНА: в тех же самых прогонах, где по #5735 ноль,
    по #3133 и #94bf окна разбираются штатно. Это и есть ПОЗИТИВНЫЙ КОНТРОЛЬ прибора
    (канон test-that-can-only-return-zero: «пусто ⇒ явления нет» законно лишь после
    позитивного контроля) — и он тут бесплатный, потому что уже лежит в той же записи.

    ПРАВИЛО. Хост припаркован, если в КАЖДОМ из n последних прогонов (а) у него ноль CU —
    неважно, отсутствием строк или явным нулём, и (б) в этом же прогоне хоть у одного
    ДРУГОГО хоста покрытое время > 0. Прогон без единого разобранного окна контролем не
    является и всё множество обнуляет: слепой сторож не имеет права объявлять тишину.

    НАЗВАННЫЙ ПРЕДЕЛ. Доказывается простой БОТА, а не аккаунта: если по ключу ходит кто-то
    ещё, здесь его не видно (канон own-meter-blind-path). Покрытия при этом не теряется —
    и книга, и хвост, которыми сторож судил ДО этой правки, ровно так же считают только
    ботовый расход; менее слепым приговор по грязному хвосту ключ не делал.
    """
    n = int(n if n is not None else PARKED_N)
    rs = sorted([r for r in recs if r.get("ts") is not None], key=lambda r: float(r["ts"]))[-n:]
    if len(rs) < n:
        return set()                      # истории меньше окна — молчать нечем, не судим
    out = set(candidates or ())
    for r in rs:
        hosts = r.get("hosts") or {}
        control = any(float(d.get("sec", 0)) > 0 for d in hosts.values())
        if not control:
            return set()                  # прогон вслепую: позитивного контроля нет
        for h in list(out):
            if float((hosts.get(h) or {}).get("cu", 0)) > 0:
                out.discard(h)
    return out

