def _lever_line(fd):
    """Какие рычаги ЕСТЬ — ВЫЧИСЛЕНИЕМ, а не вшитой строкой (канон 21.08: самоотчёт в
    шаблоне оказывается ложным ровно в той тревоге, которую сопровождает).

    Порядок жёсткий: сперва БЕСПЛАТНЫЕ (распайка запертого ведра — env/код боевого тракта),
    и только если их арифметически не хватает — деньги. 26.08 прежняя редакция звала к
    оплате, напечатав двумя строками выше 29.9M неизрасходованной бесплатной квоты.
    """
    if not fd.get("locked"):
        return "Рычага два: срезать СПРОС либо оплата/новый аккаунт."
    names = ", ".join("%s %.1fM" % (h, rem / 1e6) for h, rem, _why in fd["locked"])
    head = ("РЫЧАГ ДО ДЕНЕГ — РАСПАЙКА ЗАПЕРТОГО РЕЗЕРВА (%s): заперт он НАШЕЙ распайкой, "
            "а не биллингом, снимается кодом/env боевого тракта. " % names)
    if fd["deficit_unlocked_lo"] <= 0:
        return head + ("С ним дыра закрывается на НИЖНЕЙ границе (остаток дыры %.0f..%.0fM), "
                       "то есть ОПЛАТА/НОВЫЙ АККАУНТ ПОКА НЕ ОБОСНОВАНЫ — сперва распайка "
                       "плюс срез спроса." % (fd["deficit_unlocked_lo"] / 1e6,
                                              fd["deficit_unlocked_hi"] / 1e6))
    return head + ("Но и с ним дыра остаётся %.0f..%.0fM на обеих границах ⇒ рычаги "
                   "исчерпаны, дальше только срез СПРОСА либо оплата/новый аккаунт."
                   % (fd["deficit_unlocked_lo"] / 1e6, fd["deficit_unlocked_hi"] / 1e6))


def fleet_demand_band(recs, *, spans=SPANS_DEMAND, now=None):
    """Полоса спроса ФЛОТА (CU/сут) по нескольким хвостам сразу: [(часы, cu_в_сутки), ...].

    Считает СУММУ по всем тегам в записи — именно она инвариантна к переливу. Окно, у
    которого нет ни одной записи, в полосу не попадает (а не даёт ноль: ноль тут читался бы
    как «спроса нет», канон test-that-can-only-return-zero).
    """
    rs = [r for r in (recs or []) if r.get("until") is not None and (r.get("hosts") or {})]
    rs.sort(key=lambda r: float(r["until"]))
    out = []
    for h in spans:
        sel = rs[-int(h):]
        if len(sel) < 2:
            continue
        cu = sum(float(d.get("cu", 0)) for r in sel for d in (r.get("hosts") or {}).values())
        span = float(sel[-1]["until"]) - float(sel[0]["until"]) + 3600.0
        if span <= 0 or cu <= 0:
            continue
        out.append((int(h), cu / span * 86400.0))
    return out


def fleet_deficit(anchor, ledger, recs, *, now=None, horizon="cal", spans=SPANS_DEMAND):
    """Сумма ДОСТИЖИМЫХ остатков против интеграла спроса флота до раннего сброса.

    Возвращает dict или None, если считать нечем (нет якоря / нет полосы спроса). None —
    это «не судим», и вызывающий обязан отличать его от «дефицита нет»: молчание по
    несосчитанной величине неотличимо от здоровья (мёртвый сторож хуже отсутствующего).

    Запертым считается ведро, у которого в якоре стоит locked_reason — признак не
    вычисляется из данных и не угадывается: запертость есть свойство КОДА боевого тракта,
    и её обязан назвать человек/разбор, положив причину в якорь.
    """
    hosts = (anchor or {}).get("hosts") or {}
    if not hosts:
        return None
    band = fleet_demand_band(recs, spans=spans, now=now)
    if not band:
        return None
    now_s = float(now if now is not None else time.time())
    quota = float((anchor or {}).get("quota_cu", QUOTA_M * 1e6))
    led = (ledger or {}).get("hosts") or {}
    supply, locked = 0.0, []
    parts = []
    for h in sorted(hosts):
        mtd = float((hosts[h] or {}).get("mtd_cu", 0)) + float((led.get(h) or {}).get("cu", 0.0))
        rem = max(0.0, quota - mtd)
        reason = (hosts[h] or {}).get("locked_reason")
        if reason:
            locked.append((h, rem, str(reason)))
        else:
            supply += rem
            parts.append((h, rem))
    # Горизонт — минимальный по достижимым вёдрам: флот кончается по ПЕРВОМУ наливу не
    # раньше, чем нальётся самое позднее из них, но приговор «дыра есть» безопаснее
    # выносить по РАННЕМУ (см. границу 3).
    days = None
    for h, _rem in parts:
        spec = host_reset_spec(anchor, h, horizon=horizon)
        d = (next_reset(now_s, spec) - now_s) / 86400.0
        days = d if days is None else min(days, d)
    if days is None or days <= 0:
        return None
    lo = min(r for _h, r in band)
    hi = max(r for _h, r in band)
    # ЗАПЕРТЫЙ РЕЗЕРВ — ТРЕТИЙ РЫЧАГ, И ЕГО ОБЯЗАН СЧИТАТЬ СТОРОЖ, А НЕ РАЗБИРАЮЩИЙ.
    # 26.08 18:07 тревога напечатала «запертый резерв D 29.9M» и ТУТ ЖЕ заявила «рычага два:
    # срезать спрос либо оплата/новый аккаунт» — внутреннее противоречие, гнавшее к HIL за
    # деньгами при 29.9M НЕИЗРАСХОДОВАННОЙ БЕСПЛАТНОЙ квоты. Заперт D не биллингом, а НАШЕЙ
    # ЖЕ распайкой (spec_fire_live.py:517), то есть снимается кодом, а не оплатой. Канон
    # «у ЛЕКАРСТВА из тревоги тоже есть знаменатель» (22.08): сложить остатки и спрос ДО
    # того, как звать человека.
    locked_cu = sum(rem for _h, rem, _why in locked)
    return {
        "supply_cu": supply,
        "days_reset": days,
        "band": band,
        "demand_lo": lo * days,
        "demand_hi": hi * days,
        "deficit_lo": lo * days - supply,      # дефицит по МЯГКОЙ границе спроса
        "deficit_hi": hi * days - supply,
        "locked": locked,
        "locked_cu": locked_cu,
        # дыра, ЕСЛИ запертые вёдра распаять кодом боевого тракта: именно она отделяет
        # «нужны деньги» от «нужна одна env-строка».
        "deficit_unlocked_lo": lo * days - supply - locked_cu,
        "deficit_unlocked_hi": hi * days - supply - locked_cu,
        "hosts": parts,
    }


