# ключ был «cu-quota:balance:<host>», то есть один и тот же для ЛЮБОЙ тяжести. В инбокс уехала
# мягкая ветка (темп), тяжёлая осталась строкой в логе, которую никто не читает.
# Это третья встреча с одной формой: дедуп судит КЛЮЧ, а величину не смотрит вовсе (20.08 тем
# же способом гасился отбой ✅ ключом своей же тревоги). Лечение — НЕ трогать общий notify.py
# (радиус на весь флот) и НЕ снижать TTL (вернёт спам той же тревогой), а внести саму
# ВЕЛИЧИНУ в ключ полосами: пока тяжесть та же — дедуп работает как работал; шагнула вниз —
# это ДРУГОЙ ключ, и он проходит.
# Полоса считается по отношению «сколько ведра осталось по времени» к «сколько ждать налива»:
# r = days_zero / days_reset. r>=1 — ведро переживает сброс (ветка сюда не доходит).
# Границы 0.75/0.50/0.25 выбраны так, чтобы ухудшение ВТРОЕ (наш случай 0.84 -> 0.30) не
# могло остаться внутри одной полосы ни при каком выравнивании: три реза на отрезке [0,1)
# дают максимальную ширину полосы 4x по отношению, а мы обязаны ловить 3x.
# УЛУЧШЕНИЕ НЕ ЗВОНИТ САМО: возврат в мягкую полосу попадает на её СТАРУЮ запись дедупа
# (TTL 6ч), то есть гасится — ровно как раньше. Новый звонок минтит только НЕ ВИДЕННАЯ ещё
# полоса, а на отрезке их всего четыре ⇒ потолок дополнительного шума 3 звонка/6ч, и каждый
# несёт РЕАЛЬНОЕ ухудшение. Осцилляция «туда-обратно» бесплатна по построению.
_SEV_EDGES = (0.75, 0.50, 0.25)


def severity_band(days_zero, days_reset):
    """Полоса тяжести остатка: 0 — мягкая (ведро почти дотягивает), 3 — ведро кончится втрое
    раньше налива. Чистая функция, приёмка — юнитом на отображении, а НЕ «тревога не позвонила»:
    молчание внутри окна дедупа неотличимо от сломанной записи (тот же урок, что 26.08 по ed9e).
    """
    try:
        dz = float(days_zero)
        dr = float(days_reset)
    except (TypeError, ValueError):
        return len(_SEV_EDGES)  # незнание закрывает гард: судим по худшей полосе
    if dr <= 0 or dz != dz or dr != dr:
        # Горизонт сброса неизвестен/нулевой ⇒ отношение не определено. Худшая полоса, а не
        # мягкая: сторож не имеет права успокаивать тем, чего не измерил.
        return len(_SEV_EDGES)
    r = dz / dr
    for i, edge in enumerate(_SEV_EDGES):
        if r >= edge:
            return i
    return len(_SEV_EDGES)


# ВОДОРАЗДЕЛ ПОЛОСЫ (26.08 12:3xZ, крон-триаж тревоги cu-quota:balance:...#3133:sev1).
# ЧТО СЛОМАЛОСЬ. Фикс d75268e внёс полосу в КЛЮЧ дедупа, и его обоснование выше утверждает:
