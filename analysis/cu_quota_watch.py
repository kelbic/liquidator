# Вторая половина НЕВЕРНА, и это поймано боем в тот же день: у мягкой полосы старой записи
# НЕТ, если она ещё ни разу не звонила. 26.08 11:07Z ушёл sev2 (1.6 сут против 5.5), в
# 12:07Z запас ВЫРОС до 3.0 сут — и sev1, никогда не минтившийся, прошёл дедуп как новая
# тревога. Разбирающий читает «стало хуже на полосу» там, где стало ЛУЧШЕ.
# Это ЧЕТВЁРТАЯ встреча с формой «дедуп судит КЛЮЧ, а величину не смотрит» — и зеркальная:
# d75268e развернул ошибку (раньше глотались все повторы), а не убрал её.
# ЛЕЧЕНИЕ. Ключ по-прежнему несёт полосу (ухудшение ОБЯЗАНО проходить дедуп), но рядом
# держится ВОДОРАЗДЕЛ по хосту — худшая полоса, прозвонившая за то же окно TTL. Звонит
# строго ХУДШЕЕ; равное или мягче — строкой в лог. Осцилляция вокруг границы бесплатна.
# ПРЕДЕЛ, КОТОРЫЙ НАДО НАЗВАТЬ: водораздел живёт в cu-quota.state. Потеря файла = потеря
# памяти о тяжести ⇒ ближайший звонок пройдёт как новый. Это выбрано СОЗНАТЕЛЬНО: незнание
# обязано открывать тревогу, а не закрывать её (канон unknown-must-close-the-gate — здесь
# «гард» защищает ЧЕЛОВЕКА ОТ МОЛЧАНИЯ, поэтому безопасная сторона — позвонить).
# ПРИЁМКА — ЮНИТОМ НА ЧИСТОЙ ФУНКЦИИ, а не «тревога не позвонила»: молчание внутри окна
# дедупа неотличимо от сломанной записи (тот же урок, что 26.08 по ed9e).
def severity_should_ring(band, mark, now, ttl=21600):
    """Пропускать ли звонок полосы `band` при водоразделе `mark` = {"band":int,"ts":float}.

    True, если водораздела нет, он протух (>= ttl) или полоса СТРОГО ХУЖЕ запомненной.
    Чистая функция: ни файлов, ни времени изнутри.
    """
    if not isinstance(mark, dict):
        return True
    try:
        prev = int(mark["band"])
        ts = float(mark["ts"])
    except (KeyError, TypeError, ValueError):
        return True   # испорченная запись = памяти нет ⇒ звоним (безопасная сторона)
    if ts != ts or now - ts >= float(ttl) or now < ts:
        return True   # протухло, либо часы уехали назад — память не годится
    return int(band) > prev


def _horizon_txt(anchor, host, days_zero, days_reset, now):
    """Строка про горизонт для текста тревоги: оба кандидата и цена разницы.

    Приговор вынесен по РАННЕМУ кандидату (см. host_reset_spec). Тревога обязана это
    сказать — иначе «до сброса ещё 10.0 сут» читается как измеренный факт, каким оно не
    является: дата сброса у Alchemy владельцем не подтверждена.
    """
    base = ("дата сброса квоты НЕИЗВЕСТНА (INFRA-FACTS, проверено владельцем 21.08 — дашборд "
            "её не показывает). Взят САМЫЙ РАННИЙ кандидат (%.1f сут), а он работает В "
            "СТОРОНУ МОЛЧАНИЯ: чем позже наливается ведро, тем раньше надо звонить." % days_reset)
    a = (anchor.get("hosts") or {}).get(host) or {}
    if a.get("reset_alt") in (None, ""):
        return base + (" ВТОРОГО КАНДИДАТА НЕТ: дата заведения аккаунта неизвестна, значит "
                       "НАСКОЛЬКО поздним может быть сброс — не оценено, и дефицит ниже "
                       "может быть занижен на неизвестную величину.")
    d_alt = max(0.0, (next_reset(now, host_reset_spec(anchor, host, "alt")) - now) / 86400.0)
    return base + (" Второй кандидат (годовщина заведения, день %s): до сброса %.1f сут ⇒ "
                   "не «не хватает %.1f сут», а КЛЮЧ ТЁМНЫЙ %.1f сут. Разница между "
                   "гипотезами и есть цена висящего вопроса о дате."
                   % (a.get("reset_alt"), d_alt, max(0.0, days_reset - days_zero),
                      max(0.0, d_alt - days_zero)))


def _fetch_journal():
    r = subprocess.run(
        ["ssh", "-o", "ConnectTimeout=10", "-o", "BatchMode=yes", HOST,
         "journalctl -u liquidator-bot --since '-70 minutes' --no-pager | grep 'INFO CU ' || true"],
        capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise RuntimeError("ssh/journalctl rc=%d: %s" % (r.returncode, (r.stderr or "")[:120]))
    return r.stdout


