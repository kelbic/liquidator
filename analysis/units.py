"""Единицы денег: токен — это НЕ доллар (#30).

Дефект, живший в gap_profile.py и reachable_money.py построчно одинаково:

    repaid = int(repaidAssets) / 10 ** decimals      # -> ТОКЕНЫ
    if repaid < MIN_REPAID_USD: ...                  # -> и тут же считаются ДОЛЛАРАМИ

Для USDC-рынка совпадение случайное (курс ≈ $1), для любого другого loan-токена — ошибка на
порядки: 0.197 WETH превращались в «$0.197» вместо ~$670, то есть в 3400 раз меньше. Оба
инструмента кормят канон трёх классов («фронт», «ход до жертвы»), поэтому цифры канона были
недостоверны ровно там, где рынок не долларовый.

Тот же класс, что «цена оракула ≠ цена выхода» и «не тот объект в знаменателе»: величина
называется не тем, чем является. Лечение здесь — не угадывать курс, а РАЗДЕЛИТЬ: что можно
назвать долларом — называем, остальное считаем отдельно и ГРОМКО, а не молча приравниваем.
"""

# Loan-токены, чей курс к доллару считаем единицей. Держим список коротким и явным: лишний
# символ здесь = молчаливое возвращение того же дефекта.
USD_PEGGED = {"USDC", "USDBC", "DAI", "USDS", "USDT", "SUSDS"}


def usd_of(repaid_raw, symbol, decimals):
    """(usd, tokens) — usd=None, если loan-токен не привязан к доллару.

    Возврат None — это НЕ ошибка и не ноль: это «в долларах не выражается имеющимися данными».
    Вызывающий обязан посчитать такие строки отдельно и показать их, а не сложить с долларами."""
    try:
        tokens = int(repaid_raw or 0) / 10 ** int(decimals if decimals is not None else 18)
    except Exception:
        return (None, 0.0)
    sym = (symbol or "").strip().upper()
    return ((tokens, tokens) if sym in USD_PEGGED else (None, tokens))


def fmt_skipped(n_rows, tokens_by_symbol):
    """Строка отчёта о том, что НЕ попало в долларовые суммы. Пустая строка — если всё попало."""
    if not n_rows:
        return ""
    parts = ", ".join("%s %.4f" % (s, v) for s, v in sorted(tokens_by_symbol.items()))
    return ("ВНЕ ДОЛЛАРОВОГО СЧЁТА: %d строк на не-стейбл loan-токенах (%s) — "
            "в суммы выше НЕ включены (курс не известен инструменту)" % (n_rows, parts))
