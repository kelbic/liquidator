sys.path.insert(0, str(pathlib.Path(__file__).parent))

import chain.chain_index as ci                                # noqa: E402

BN0 = 49890266
LOGGER = logging.getLogger("liquidator")


class Cap(logging.Handler):
    def __init__(self):
        super().__init__()
        self.errs, self.warns, self.infos = [], [], []

    def emit(self, rec):
        m = rec.getMessage()
        (self.errs if rec.levelno >= logging.ERROR
         else self.warns if rec.levelno >= logging.WARNING else self.infos).append(m)


def drill(freeze_after_sec=60.0, seconds=300, shed=False, kill_health=False,
          health_once=False):
    """Прогоняет `seconds` МОДЕЛЬНЫХ секунд жизни индекса. Голова замирает после N секунд.

    shed: False | True | (t0, t1) — окно уступки ключа бою В МОДЕЛЬНЫХ секундах от старта.
    health_once: МУТАЦИЯ «надзор отчитался один раз и замолк» (проверка самой дрели).
    """
    T = [1000.0]
    calls = {"head": 0}

    def _http(url, payload, timeout):
        m = payload["method"]
        elapsed = T[0] - 1000.0
        head = BN0 + int(min(elapsed, freeze_after_sec) // 2)     # блок Base = 2с
        if m == "eth_blockNumber":
            calls["head"] += 1
            return {"result": hex(head)}
        if m == "eth_getLogs":
            return {"result": []}
        return {"result": None}

    idx = ci.ChainIndex("https://node.test/KEY", watch_to=["0x" + "ab" * 20], http=_http,
                        now=lambda: T[0], sleep=lambda s: None)
    if kill_health:
        idx._health = lambda: None            # МУТАЦИЯ: механизм надзора снят
    if health_once:
        # МУТАЦИЯ «ОДИН РАЗ И ЗАМОЛК»: механизм НЕ вырезан, снята только ПЕРИОДИЧНОСТЬ.
        _real_health, _done = idx._health, []

        def _once():
            if _done:
                return
            _was = idx._health_ts                 # отчёт СОСТОЯЛСЯ, а не «вызов был»
            _real_health()
            if idx._health_ts != _was:
                _done.append(1)
        idx._health = _once
    if shed is True:
        idx._shed = lambda: True
    elif isinstance(shed, tuple):
        idx._shed = lambda: shed[0] <= (T[0] - 1000.0) < shed[1]
    cap = Cap()
    cap.setLevel(logging.DEBUG)
    LOGGER.addHandler(cap)
    # Боевой уровень журнала — INFO (config.py: log_level="INFO"), и строка «ЧИТАЮ ЦЕПЬ» идёт
    # именно на нём: раз в 120с положительное утверждение о живости в журнал попадать обязано,
    # а тревога («ЗАМОРОЖЕН») уходит на ERROR и переживает любое прореживание.
    _sv_lvl = LOGGER.level
    LOGGER.setLevel(logging.INFO)
    _sv_poll = ci.CHAIN_INDEX_SELF_POLL_SEC
    ci.CHAIN_INDEX_SELF_POLL_SEC = 1.0
    class _Wake(object):
        """ЧАСЫ ПЕТЛИ ДВИГАЕТ САМ ТРЕД ИНДЕКСА (B4 р-7): модельное время идёт РОВНО внутри
        собственного ожидания петли, а не по реальным часам главного треда. Прежняя редакция
        (`T += шаг; _wake.set(); time.sleep(0.0015)`) надеялась, что настоящий тред успеет
        отработать оборот за 1.5мс: под нагрузкой не успевал, и прибор давал ложный диагноз на
        проектной норме. Показания прибора не имеют права зависеть от загрузки машины."""

        def __init__(self, step, stop_at, on_tick=None):
            self.step, self.stop_at, self.on_tick = step, stop_at, on_tick

        def wait(self, timeout=None):
            T[0] += self.step
            if self.on_tick is not None:
                self.on_tick()
            if (T[0] - 1000.0) >= self.stop_at:
                idx._stop.set()
            return False

        def set(self):
            pass

        def clear(self):
            pass

        def is_set(self):
            return False

    idx._wake = _Wake(1.0, seconds)
    try:
        idx._stop.clear()
        idx._loop()
    finally:
        ci.CHAIN_INDEX_SELF_POLL_SEC = _sv_poll
        LOGGER.setLevel(_sv_lvl)
        LOGGER.removeHandler(cap)
    return idx, cap


# ---------------------------------------------------------------- 1. голова замерла на 60-й
idx, cap = drill()
s = idx.snapshot()
assert s["blocks"] > 0, "дрель бессмысленна, если индекс и не начинал читать: %s" % s
assert s["fresh"] is False, "голова замерла — индекс ОБЯЗАН быть протухшим: %s" % s
_accept = [m for m in cap.warns + cap.errs if "CHAIN-INDEX ПРИЁМКА" in m]
assert _accept and "МЁРТВ" not in _accept[0], \
    ("одноразовая приёмка первой минуты обязана была отчитаться положительно — именно поэтому "
     "её одной и не хватает: %s" % _accept)
assert "ВЕРДИКТ: ЧАСТИЧНО" in _accept[0], \
    ("в дрели узел не отдаёт интересных логов, значит полных чтений НОЛЬ — приёмка «а» "
     "требует полных>0 и обязана это РАЗЛИЧАТЬ, а не звать «ЖИВ»: %s" % _accept[0])
_froze = [m for m in cap.errs if "ЗАМОРОЖЕН" in m]
assert _froze, ("заморозка после 60-й секунды обязана быть ERROR, а не тишиной. "
                "ERROR за прогон: %s" % cap.errs)
assert "CHAIN-INDEX ЖИВОСТЬ(120с)" in _froze[0] and "всего: блоков=%d" % s["blocks"] in _froze[0], \
    _froze[0]
# ПОВТОРНОСТЬ, а не факт одного отчёта (р-3): надзор ради того и заведён, чтобы говорить В
# КАЖДОМ окне 2..N. `>=1` принимал мутацию «отчитался один раз и замолк» — тот же дефект
# этажом ниже. Прогон 300 модельных секунд при периоде 120с даёт ровно два окна.
assert len(_froze) >= 2, \
    ("надзор обязан ПОВТОРЯТЬСЯ в окнах 2..N, а не отчитаться один раз: ERROR-строк %d (%s)"
     % (len(_froze), cap.errs))
assert idx.stats["stale_events"] >= 2, idx.stats
assert "подряд здоровых=0" in _froze[-1], \
    "счётчик подряд-здоровых обязан обнуляться на тревоге: %s" % _froze[-1]
print("UNIT_OK: голова узла замерла ПОСЛЕ приёмочной строки «ЖИВ» — 120с-строка выдала ERROR "
      "«ЗАМОРОЖЕН» %d раз(а) (ПОВТОРНО, окна 2..N), stale_events=%d"
      % (len(_froze), idx.stats["stale_events"]))

# ------------------------------- 1b. МУТАЦИЯ «отчитался один раз и замолк» обязана КРАСНИТЬ
