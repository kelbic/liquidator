"""L2 р-8, ВТОРОЙ ЭШЕЛОН: отрицательная дельта позиций невозможна ПО ПОСТРОЕНИЮ.

ЗАЧЕМ ОТДЕЛЬНЫЙ ТЕСТ. Первый эшелон починки L2 — когерентность клейма кольцу (клеймо уходит
из `_probe_claim` в той же точке, где ключ уходит из `_probe_by_key`). Его проверяет чужой
прибор `l2_claim_outlives_ring.py`. Но у починки есть ВТОРАЯ половина — зажим пола отсчёта
текущим значением счётчика, — и прибор к ней СЛЕП: при живой когерентности пол никогда не
превышает факт, поэтому снятие зажима прибор не краснит (проверено мутацией M3b: прибор
остаётся ЗЕЛЁНЫМ). Незакрытая половина — это «маловероятно» вместо «невозможно», а ровно
такие половины и возвращались новым механизмом два раунда подряд.

Здесь состояние «пол больше факта» создаётся ПРЯМО, на настоящем `_probe_delta`: так выглядит
карта после вытеснения ключа кольцом при любом источнике пола (снимок окна на арме ИЛИ клеймо
закрывшегося соседа). Оба источника проверяются по отдельности.

ПОЗИТИВНЫЙ КОНТРОЛЬ обязателен: тест, который может вернуть только ноль, ничего не измеряет.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import chain.spec_fire_live as sfl                                  # noqa: E402

KEY = ("0x" + "a1" * 32, "0x" + "b1" * 20)


def mk():
    s = sfl.SpecFireLive.__new__(sfl.SpecFireLive)
    s.stats = {}
    s._probe_by_key = {}
    s._probe_claim = {}
    s._plan_key_by_feed = {}
    s._board = {}
    return s


def negatives(d):
    return {k: v for k, v in d.items() if isinstance(v, int) and v < 0}


sf = mk()
# КАРТА ПОСЛЕ ВЫТЕСНЕНИЯ: ключ завели заново, по нему 9 своих проб.
sf._probe_by_key[KEY] = {"probe_landed": 9, "probe_judged": 9, "probe_no_agg": 9}

# --- 1. ПОЛ ИЗ СНИМКА ОКНА (окно армилось ДО вытеснения и помнит 50) --------------------
snap = {"by_key": {KEY: {"probe_landed": 50, "probe_judged": 50, "probe_no_agg": 50}},
        "all": {k: 0 for k in sf._PROBE_KEYS}}
out = sf._probe_delta(snap, KEY)
assert not negatives(out), "снимок окна пережил счётчики и дал минус: %s" % out
print("OK 1/3: пол из снимка окна выше факта -> нулей достаточно, минуса нет: %s" % out)

# --- 2. ПОЛ ИЗ КЛЕЙМА СОСЕДА (сосед засчитал 50, кольцо счётчики выбросило) -------------
empty = {"by_key": {}, "all": {k: 0 for k in sf._PROBE_KEYS}}
out2 = sf._probe_delta(empty, KEY,
                       floor={"probe_landed": 50, "probe_judged": 50, "probe_no_agg": 50})
assert not negatives(out2), "клеймо соседа пережило счётчики и дало минус: %s" % out2
print("OK 2/3: пол из клейма соседа выше факта -> минуса нет: %s" % out2)

# --- 3. ПОЗИТИВНЫЙ КОНТРОЛЬ: зажим не превращает измеритель в генератор нулей -----------
# Тот же объект, та же функция, законный случай: своих проб 9 при поле 4 -> обязано быть 5.
out3 = sf._probe_delta(empty, KEY,
                       floor={"probe_landed": 4, "probe_judged": 4, "probe_no_agg": 4})
assert out3.get("probe_landed") == 5, "зажим съел законную дельту: %s" % out3
assert out3.get("probe_judged") == 5 and out3.get("probe_no_agg") == 5, out3
print("OK 3/3: ПОЗИТИВНЫЙ КОНТРОЛЬ — законный пол ниже факта даёт настоящую дельту: %s" % out3)

print("=== L2 второй эшелон: отрицательная дельта невозможна по построению ===")
